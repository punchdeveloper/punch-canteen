/**
 * One-off build step used during the rebuild (kept for traceability).
 *
 * Input:  the v63 CSS reduced to the 500 rules that the live site actually
 *         used (measured in the browser on every screen at 1280/768/390px).
 * Output: src/app/styles/v63.css — the same rules, mechanically adjusted:
 *   * Google Font @imports removed (fonts are loaded by next/font instead,
 *     and referenced through CSS variables);
 *   * `nav button` selectors also match links (navigation is now <a>);
 *   * rules for things the rebuild no longer renders are dropped
 *     (start-up splash, "LOCAL DEMO" badge, top notice).
 * Usage: node scripts/build-canteen-css.mjs <used.css>
 */
import fs from "node:fs";
import postcss from "postcss";

const [input] = process.argv.slice(2);
const root = postcss.parse(fs.readFileSync(input, "utf8"));

const DROP = /punch-startup|punch-booting|\.demo\b|main>\.notice|nav button:before|nav button\[data-go=/;

root.walkAtRules("import", (at) => at.remove());
root.walkRules((rule) => {
  if (DROP.test(rule.selector)) return rule.remove();
  rule.selector = rule.selector
    .replace(/#mobile-bottom-nav button/g, "#mobile-bottom-nav :is(button,a)")
    .replace(/(^|[\s,>])nav button/g, "$1nav :is(button,a)");
});
root.walkAtRules("keyframes", (at) => at.remove());
root.walkAtRules((at) => {
  if (/^(media|supports)$/.test(at.name) && !at.nodes?.length) at.remove();
});
root.walkDecls((d) => {
  d.value = d.value
    .replace(/'Comic Neue'/g, "var(--font-comic)")
    .replace(/"DM Sans"|'DM Sans'/g, "var(--font-dm-sans)")
    .replace(/'Lora'/g, "var(--font-lora)");
});

const header = `/* =============================================================================
   PUNCH Canteen — v63 visual design, carried over unchanged.
   Generated by scripts/build-canteen-css.mjs from the rules the live v63 site
   actually used. Do not hand-edit layout fixes here: they live in fixes.css,
   which loads after this file.
   ============================================================================= */
`;
const out = header + root.toString().replace(/\n{3,}/g, "\n\n");
fs.mkdirSync("src/app/styles", { recursive: true });
fs.writeFileSync("src/app/styles/v63.css", out);
console.log(`wrote src/app/styles/v63.css (${out.length} bytes)`);
